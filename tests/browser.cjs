const assert = require("node:assert/strict");
const path = require("node:path");
const fs = require("node:fs/promises");
const { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.MEMOIR_PLAYWRIGHT || "playwright");
const root = path.resolve(__dirname, "..");
const base = process.env.MEMOIR_URL || pathToFileURL(root + path.sep).href;
async function run() {
    const browser = await chromium.launch({ executablePath: process.env.MEMOIR_BROWSER || undefined, headless: true });
    try {
        const ctx = await browser.newContext({ viewport: { width: 1366, height: 820 }, locale: "zh-CN", acceptDownloads: true });
        const p = await ctx.newPage();
        p.setDefaultTimeout(5000);
        const errors = [];
        p.on("pageerror", e => errors.push(e.message));
        p.on("response", r => { if (r.status() >= 400)
            errors.push(`${r.status()} ${r.url()}`); });
        const button = (name, scope = p) => scope.getByRole("button", { name, exact: true });
        const submit = async () => { await p.locator("#submit").click(); await p.locator("#modal").waitFor({ state: "hidden" }); };
        const nav = async (name) => { await button(name, p.locator("#bottom-nav")).click(); };
        async function fits() {
            assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "水平溢出 " + p.url());
        }
        await p.goto(base + "index.html");
        await p.getByRole("link", { name: /逛逛官网/ }).click();
        await fits();
        assert(await p.locator(".polaroid img").evaluate(i => i.complete && i.naturalWidth > 0));
        await p.locator("#sample-task").click();
        assert.equal(await p.locator("#sample-task").getAttribute("aria-pressed"), "true");
        await p.locator("#sample-mood").click();
        assert.match(await p.locator("#sample-mood").innerText(), /低落/);
        await button("规划").click();
        assert.equal(await p.locator(".template").count(), 2);
        await p.locator("#simulate").click();
        await p.frameLocator("iframe").getByRole("heading", { name: "今天这一页" }).waitFor();
        await button("关闭预览").click();
        await p.locator("#try-title").fill("蓝调散步");
        await p.locator("#try-text").fill("记录 <今天> & 晚风");
        await button("贴纸 🌙").click();
        assert.equal(await p.locator("#live-sticker").innerText(), "🌙");
        await p.setViewportSize({ width: 390, height: 844 });
        await fits();
        await p.locator("#take-draft").click();
        assert.equal(await p.locator("[name=title]").inputValue(), "蓝调散步");
        await submit();
        await p.locator("[data-note]").first().click();
        await button("编辑手记").click();
        assert.equal(await p.locator(".block textarea").inputValue(), "记录 <今天> & 晚风");
        await button("＋ 添加内容块").click();
        const block = p.locator(".block").last();
        await block.locator("select").selectOption("图片");
        await block.locator("input[type=file]").setInputFiles(path.join(root, "mobile_app", "assets", "logo.png"));
        await block.locator("textarea").fill("照片说明");
        await button("＋ 添加内容块").click();
        const item = p.locator(".block").last();
        await item.locator("select").selectOption("清单");
        await item.locator("textarea").fill("收拾照片");
        await item.locator("input[type=checkbox]").check();
        await p.locator("[name=tape]").check();
        await submit();
        await p.reload();
        await nav("手账本");
        await p.locator("#find-note").fill("晚风");
        assert.equal(await p.locator("[data-note]").count(), 1);
        await p.locator("[data-note]").click();
        assert(await p.locator(".read-check input").isChecked());
        await button("编辑手记").click();
        assert.equal(await p.locator(".block").count(), 3);
        assert(await p.locator(".block img:visible").evaluate(i => i.complete && i.naturalWidth > 0));
        assert(await p.locator(".block").last().locator("input[type=checkbox]").isChecked());
        await button("关闭").click();
        await nav("计划");
        await button("＋ 任务").click();
        await p.locator("[name=title]").fill("晚上散步");
        await p.locator("[name=high]").check();
        await p.locator("[name=time]").fill("19:15");
        await submit();
        await p.locator("[data-task-toggle]").click();
        await button("未完成").click();
        assert.equal(await p.locator("[data-task-toggle]").count(), 0);
        await button("优先").click();
        assert.equal(await p.locator("[data-task-toggle]").getAttribute("aria-pressed"), "true");
        await button("＋ 新习惯").click();
        await p.locator("[name=name]").fill("喝水");
        await submit();
        await button("喝水打卡").click();
        assert.equal(await button("喝水打卡").getAttribute("aria-pressed"), "true");
        await button("喝水打卡").click();
        assert.equal(await button("喝水打卡").getAttribute("aria-pressed"), "false");
        await nav("日页");
        await p.locator("[data-mood='1']").click();
        await p.locator("[name=level]").fill("4");
        await p.locator("[name=tag]").fill("独处");
        await submit();
        assert.match(await p.locator("#screen").innerText(), /强度 4\/5 独处/);
        await p.locator("#pick-date").click();
        await p.locator("[name=day]").fill("2024-02-29");
        await submit();
        assert.equal(await p.locator("[data-task-toggle]").count(), 0);
        await nav("我的");
        await button("鼠尾草").click();
        assert.equal(await p.locator("body").getAttribute("data-paper"), "sage");
        await button("＋ 新空间").click();
        await p.locator("[name=name]").fill("旅行");
        await submit();
        await button("旅行").click();
        assert.equal(await p.locator("#note-space").inputValue(), "旅行");
        await nav("我的");
        const downloading = p.waitForEvent("download");
        await button("导出备份").click();
        const download = await downloading, backup = JSON.parse(await fs.readFile(await download.path(), "utf8"));
        assert.equal(backup.notes.length, 1);
        assert.equal(backup.tasks.length, 1);
        assert.equal(backup.feelings[0].level, 4);
        await button("恢复备份").click();
        const fileInput = p.locator("[name=backup]");
        await fileInput.setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from("{}") });
        await p.locator("#submit").click();
        await p.getByText("备份格式无效，当前记录已保留。").waitFor();
        backup.notes[0].title = "备份恢复成功";
        await fileInput.setInputFiles({ name: "restore.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(backup)) });
        p.once("dialog", d => d.accept());
        await submit();
        await nav("手账本");
        assert.match(await p.locator("[data-note]").innerText(), /备份恢复成功/);
        await p.goto(base + "website/index.html#templates");
        await p.locator(".template").first().click();
        assert.equal(await p.locator("[name=title]").inputValue(), "晨间一页");
        await submit();
        await p.setViewportSize({ width: 320, height: 700 });
        for (const name of ["日页", "手账本", "计划", "我的"]) {
            await nav(name);
            await fits();
        }
        await p.setViewportSize({ width: 1280, height: 800 });
        await button("日页", p.locator("#side-nav")).click();
        await fits();
        assert.deepEqual(errors, []);
        console.log("PASS: portal, site demo, filters, simulator, drafts, templates, blocks, image, checklist, reload, search, tasks, habits, moods, calendar, spaces, theme, backup validation + restore, responsive layout, browser errors");
        await ctx.close();
    }
    finally {
        await browser.close();
    }
}
run().catch(e => { console.error(e); process.exitCode = 1; });
